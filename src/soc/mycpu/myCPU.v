                x2_valid && x2_is_mul && mul_queue_select_next;
            m2_mul_queue_select_mask_r <=
                {32{x2_valid && x2_is_mul && mul_queue_select_next}};
        end

        if (cpu_rstn) begin
            m2_control_ready_of_r <=
                m2_branch_result_available_next |
                (m2_branch_is_load_next && load_capture_accept);
            m2_load_available_of_r <=
                m2_branch_is_load_next && load_capture_accept;
            m2_load_unavailable_of_r <=
                m2_branch_is_load_next && !load_capture_accept;
        end
    end
`ifndef SYNTHESIS
    // The next-state metadata above is an exact retiming of the ALU queue
    // state, not a prediction heuristic.  Exercise this invariant throughout
    // simulation so an alignment error can never be hidden by benchmark data.
    always @(posedge cpu_clk) begin
        if (cpu_rstn && mem_valid && mem_is_mul &&
            m2_mul_result_ready_r && !mul_result_valid)
            $fatal(1, "M2 MUL metadata asserted before result availability");
        if (cpu_rstn &&
            (m2_control_ready_of_r !==
             (m2_branch_result_available_r |
              (m2_branch_is_load_r && load_result_valid_of_r))))
            $fatal(1, "M2 OF control-ready shadow lost cycle alignment");
        if (cpu_rstn &&
            (m2_load_available_of_r !==
             (m2_branch_is_load_r && load_result_valid_of_r)))
            $fatal(1, "M2 OF Load-available shadow lost cycle alignment");
        if (cpu_rstn &&
            (m2_load_unavailable_of_r !==
             (m2_branch_is_load_r && !load_result_valid_of_r)))
            $fatal(1, "M2 OF Load-unavailable shadow lost cycle alignment");
    end
`endif
    // load_result_valid_r/data_r are CPU-clocked registers.  This local type
    // replica replaces the former generic MEM rf_we/wd_sel/result-ready cone.
    wire m2_branch_load_available = m2_load_available_of_r;
    // These gates are consumed only by their matching request class inside
    // EX2.  Re-testing m1_load_predec/m1_store_predec here is functionally
    // redundant (a zero request remains zero when gated) and creates a
    // request -> class-reduce -> block -> request combinational feedback cone.
    // Keep the block inputs class-local without feeding the request back into
    // its own final enable.  This is an exact Boolean simplification and adds
    // neither a pipeline stage nor a performance bubble.
    wire m1_read_block  = ldst_suspend | m1_store_load_conflict_r;
    wire m1_write_block = ldst_suspend | store_buffer_full;

    // AddressTranslate only replaces vaddr[31:29] for a DMW hit.  Capture
    // those translated high bits on the existing EX->M1 edge and retain the
    // low 29 ALU bits from the normal x2 register.  This preserves the exact
    // M1 physical address and request cycle, but removes DMW hit/mux logic from
    // the DCache Store-shadow/FIFO payload path.
    always @(posedge cpu_clk) begin
        if (!cpu_rstn)
            m1_daccess_paddr_hi <= 3'b0;
        else if (!pl_suspend)
            m1_daccess_paddr_hi <= ex_daccess_paddr[31:29];
    end
    assign m1_daccess_paddr = {m1_daccess_paddr_hi,
                               m1_daccess_vaddr[28:0]};
    // OF normally waits for an unavailable result.  The one exception remains
    // a Store whose address is final while only its data depends on an older
    // Load; that dependency tag is filled by the registered Load result in M1.
    // A non-zero ram_we is emitted only for ST.B/ST.H/ST.W; every one of
    // those instructions also selects WD_RAM.  The WD selector comparison
    // was therefore redundant, while placing its high-fanout EX register in
    // the early-load hold and ID-boundary control cone.
    wire ex_store_data_load_dep = ex_valid &&
                                  (ex_ram_we != `RAM_WE_N) &&
                                  ex_load_dep_r2 && !ex_load_dep_r1;
`ifndef SYNTHESIS
    wire ex_store_data_load_dep_reference = ex_valid &&
                                  (ex_wd_sel == `WD_RAM) &&
                                  (ex_ram_we != `RAM_WE_N) &&
                                  ex_load_dep_r2 && !ex_load_dep_r1;
    always @(posedge cpu_clk) begin
        if (cpu_rstn &&
            (ex_store_data_load_dep !==
             ex_store_data_load_dep_reference))
            $fatal(1, "Store-data Load dependency class changed");
    end
`endif
    // Absorb the Store-data exception into the dependency expression.  This
    // is the same truth table as "any Load dependency && !exception", but it
    // lets early_load_hold be formed in one local LUT instead of traversing
    // the separately consumed ex_store_data_load_dep node.
    assign early_load_hold = load_request && ex_valid &&
                             (ex_load_dep_r1 ||
                              (ex_load_dep_r2 &&
                               (ex_ram_we == `RAM_WE_N)));
`ifndef SYNTHESIS
    wire early_load_hold_reference = load_request && ex_valid &&
                             (ex_load_dep_r1 || ex_load_dep_r2) &&
                             !ex_store_data_load_dep_reference;
    always @(posedge cpu_clk) begin
        if (cpu_rstn &&
            (early_load_hold !== early_load_hold_reference))
            $fatal(1, "absorbed early Load hold changed");
    end
`endif

    // ---------------------------------------------------------------------
    // Precise Store -> Load disambiguation
    // ---------------------------------------------------------------------
    // Compare the younger EX Load against every older Store which has not yet
    // entered DCache's ordered write FIFO.  A Store accepted on this edge is
    // deliberately excluded: cache_wreq_bridge captures it into its own
    // registered address shadow and ticket before this Load can issue in M1.
    // The Store currently in M1 is checked separately because it enqueues on
    // the same edge on which the younger Load crosses EX->M1.
    wire ex_order_load = ex_valid && !early_load_hold &&
                         (ex_wd_sel == `WD_RAM) &&
                         (ex_ram_we == `RAM_WE_N);
    wire [20:0] ex_load_word_key = ex_order_addr_key[20:0];
    // AddressTranslate changes only [31:29].  Therefore any physical
    // 1F00_xxxx/BFD0_xxxx access necessarily retains one of these two
    // [28:16] patterns.  Treat every segment alias of those windows as MMIO;
    // this cannot miss a peripheral access and removes DMW logic from the
    // conflict-register input path.
    wire ex_load_peripheral =
                         (ex_order_addr_key[26:14] == 13'h1F00) ||
                         (ex_order_addr_key[26:14] == 13'h1FD0);
    wire ex_order_addr_late = ex_load_dep_r1 || ex_mul_dep_r1;

    // When two entries are present both slots are valid.  With one entry only
    // store_rd_ptr selects the valid slot.  Exclude the head if it is retiring
    // on this edge; the DCache shadow assumes ordering responsibility then.
    wire store_entry0_valid = store_buffer_full ||
                              (store_buffer_busy && !store_rd_ptr);
    wire store_entry1_valid = store_buffer_full ||
                              (store_buffer_busy &&  store_rd_ptr);
    wire store_entry0_pending = store_entry0_valid &&
                                !(store_pop && !store_rd_ptr);
    wire store_entry1_pending = store_entry1_valid &&
                                !(store_pop &&  store_rd_ptr);

    wire store_entry0_conflict = store_entry0_pending &&
                                 (ex_load_peripheral ||
                                  store_peripheral_mem[0] ||
                                  (store_word_key_mem[0] ==
                                   ex_load_word_key));
    wire store_entry1_conflict = store_entry1_pending &&
                                 (ex_load_peripheral ||
                                  store_peripheral_mem[1] ||
                                  (store_word_key_mem[1] ==
                                   ex_load_word_key));
    wire m1_store_peripheral =
                         (m1_daccess_paddr[31:16] == 16'h1F00) ||
                         (m1_daccess_paddr[31:16] == 16'hBFD0);
    // m1_store_predec is the registered raw request class.  If its local write
    // gate is open, the Store will enqueue on this boundary; using the raw
    // class also keeps the EX comparison independent of EX2's final pulse mux.
    wire current_m1_store_enqueues = m1_store_predec && !m1_write_block;
    wire current_m1_store_conflict = current_m1_store_enqueues &&
                                     (ex_load_peripheral ||
                                      m1_store_peripheral ||
                                      (m1_daccess_paddr[22:2] ==
                                       ex_load_word_key));
    wire any_cpu_older_store = store_entry0_pending ||
                               store_entry1_pending ||
                               current_m1_store_enqueues;
    wire precise_store_load_conflict = store_entry0_conflict ||
                                       store_entry1_conflict ||
                                       current_m1_store_conflict;
    wire ex_store_load_conflict = ex_order_load &&
                                  (ex_order_addr_late ?
                                   any_cpu_older_store :
                                   precise_store_load_conflict);

    // Launch one stage early only when the local Store queue is empty and no
    // Store is entering it on this edge.  The registered CDC shadow still
    // enforces ordering against Stores already handed to DCache, while the
    // early-request timing cone remains independent of the address CAM.
    assign daccess_early_valid = ex_load_probe_valid && !pl_suspend &&
                                 !ex_store_load_conflict;
    assign daccess_early_addr  = ex_daccess_paddr;

    // A dependent Load waits until the CPU-side queue has transferred the
    // matching Store(s) into DCache's registered ordered queue.  Waiting for
    // the tiny two-entry queue to drain avoids a live compare on the M1
    // release path.  Unrelated Loads never set this bit and issue normally.
    always @(posedge cpu_clk) begin
        if (!cpu_rstn)
            m1_store_load_conflict_r <= 1'b0;
        else if (!pl_suspend)
            m1_store_load_conflict_r <= ex_store_load_conflict;
        else if (m1_store_load_conflict_r &&
                 (store_last_retire || !store_buffer_busy))
            m1_store_load_conflict_r <= 1'b0;
    end
    // ID2 classifies each source dependency once.  The resulting one-hot tag
    // is captured by OF and moves with the producer through EX/M1/M2/WB.
    // Consequently OF forwarding and branch resolution no longer repeat four
    // live 5-bit destination comparisons in their result/redirect cone.
    wire id_r1_of_match = of_valid && of_rf_we && (of_wR != 5'd0) &&
                          id_rR1_re && (id_rR1 == of_wR);
    wire id_r2_of_match = of_valid && of_rf_we && (of_wR != 5'd0) &&
                          id_rR2_re && (id_rR2 == of_wR);
    wire id_r1_ex_match = ex_valid && ex_rf_we && (ex_wR != 5'd0) &&
                          id_rR1_re && (id_rR1 == ex_wR);
    wire id_r2_ex_match = ex_valid && ex_rf_we && (ex_wR != 5'd0) &&
                          id_rR2_re && (id_rR2 == ex_wR);
    wire id_r1_m1_match = x2_valid && x2_rf_we && (x2_wR != 5'd0) &&
                          id_rR1_re && (id_rR1 == x2_wR);
    wire id_r2_m1_match = x2_valid && x2_rf_we && (x2_wR != 5'd0) &&
                          id_rR2_re && (id_rR2 == x2_wR);
    wire id_r1_m2_match = mem_valid && mem_rf_we && (mem_wR != 5'd0) &&
                          id_rR1_re && (id_rR1 == mem_wR);
    wire id_r2_m2_match = mem_valid && mem_rf_we && (mem_wR != 5'd0) &&
                          id_rR2_re && (id_rR2 == mem_wR);

    // Tag bit order is {EX, M1, M2, WB} as observed after the capture edge.
    // The resident OF producer becomes EX.  A held EX remains EX; otherwise
    // the old EX advances to M1.  M1 and M2 always advance when ID2 can issue.
    wire [3:0] id_r1_dep_tag =
        id_r1_of_match ? 4'b1000 :
        id_r1_ex_match ? (early_load_hold ? 4'b1000 : 4'b0100) :
        id_r1_m1_match ? 4'b0010 :
        id_r1_m2_match ? 4'b0001 : 4'b0000;
    wire [3:0] id_r2_dep_tag =
        id_r2_of_match ? 4'b1000 :
        id_r2_ex_match ? (early_load_hold ? 4'b1000 : 4'b0100) :
        id_r2_m1_match ? 4'b0010 :
        id_r2_m2_match ? 4'b0001 : 4'b0000;

    wire id_src_of_match = id_r1_of_match | id_r2_of_match;
    wire id_src_ex_match = id_r1_ex_match | id_r2_ex_match;
    wire id_src_m1_match = id_r1_m1_match | id_r2_m1_match;
    wire id_src_m2_match = id_r1_m2_match | id_r2_m2_match;

    // Verification-visible stage classifications retained for the existing
    // full-platform performance monitor.  They no longer control ID2 stalls.
    wire ex_branch_use = id_is_br_jmp && id_src_ex_match;
    wire x2_branch_use = id_is_br_jmp && id_src_m1_match;
    wire mem_branch_use = id_is_br_jmp && id_src_m2_match;
    wire ex_load_use = id_src_ex_match && (ex_wd_sel == `WD_RAM);
    wire x2_load_use = id_src_m1_match && (x2_wd_sel == `WD_RAM);
    wire mem_load_use = id_src_m2_match && (mem_wd_sel == `WD_RAM) &&
                        !mem_load_result_available;

    assign id_branch_deferred = id_is_br_jmp &&
                                (id_src_of_match | id_src_ex_match |
                                 id_src_m1_match | id_src_m2_match);

    // CPUCFG/CSR/CACOP keep their conservative serialization contract so the
    // ID2-computed payload observes the final WB value.  Evaluate their live
    // producer match behind a one-bit register: allowing the generic M2
    // destination compare to drive the common ID2->OF payload enable created
    // hundreds of route-dominated CE paths.  A newly captured system
    // instruction spends one local check cycle in ID2; ordinary instructions
    // never consult these registers.
    wire system_live_data_match =
        id_src_of_match | id_src_ex_match |
        id_src_m1_match | id_src_m2_match;
    reg id_system_checked_r;
    reg id_system_data_wait_r;
    always @(posedge cpu_clk) begin
        if (!cpu_rstn || front_redirect_valid) begin
            id_system_checked_r  <= 1'b0;
            id_system_data_wait_r <= 1'b0;
        end else if (ibuf_pop) begin
            id_system_checked_r  <= 1'b0;
            id_system_data_wait_r <= 1'b0;
        end else if (!id_waiting || !id_is_system) begin
            id_system_checked_r  <= 1'b0;
            id_system_data_wait_r <= 1'b0;
        end else if (!pl_suspend) begin
            id_system_checked_r  <= 1'b1;
            id_system_data_wait_r <= system_live_data_match;
        end
    end
    wire id_system_issue_wait =
        id_is_system &&
        (!id_system_checked_r || id_system_data_wait_r ||
         store_pipeline_pending);
    wire system_pipe_busy = |sys_valid_pipe |
                            (of_valid && of_is_system);

    // A deferred OF branch owns the single BPU update port.  Only another
    // branch/false-positive taken prediction must wait; ordinary issue remains
    // one instruction per cycle.
    wire branch_resolve_conflict = of_deferred_resolve && id_waiting &&
                                   (id_is_br_jmp || id_pred_taken);
    wire ex_deferred_resolve = of_deferred_resolve;

    // ---------------------------------------------------------------------
    // Restricted dual-issue dependency checks
    // ---------------------------------------------------------------------
    // Slot-1 results enter only the ID2->OF operand-register D cone, beginning
    // at the registered M1 boundary.  They never feed ID1 capture, the ID2
    // branch comparator or redirect logic.  OF/EX lane-1 matches therefore
    // wait; M1/M2/WB matches can capture a final value into OF.  WB2 refresh in
    // ID1_ID2 remains the persistent fallback if a consumer is held longer.
    wire s0_of_producer = of_valid && of_rf_we && (of_wR != 5'd0);
    wire s1_of_producer = s1_of_valid && s1_of_rf_we && (s1_of_wR != 5'd0);
    wire s1_ex_producer = s1_ex_valid && s1_ex_rf_we && (s1_ex_wR != 5'd0);
    wire s1_m1_producer = s1_m1_valid && s1_m1_rf_we && (s1_m1_wR != 5'd0);
    wire s1_m2_producer = s1_m2_valid && s1_m2_rf_we && (s1_m2_wR != 5'd0);
    wire s1_wb_producer = s1_wb_valid && s1_wb_rf_we && (s1_wb_wR != 5'd0);

    wire id_r1_s1_of_match = id_rR1_re && (id_rR1 != 5'd0) &&
                              s1_of_producer && (id_rR1 == s1_of_wR);
    wire id_r1_s1_ex_match = id_rR1_re && (id_rR1 != 5'd0) &&
                              s1_ex_producer && (id_rR1 == s1_ex_wR);
    wire id_r1_s1_m1_match = id_rR1_re && (id_rR1 != 5'd0) &&
                              s1_m1_producer && (id_rR1 == s1_m1_wR);
    wire id_r1_s1_m2_match = id_rR1_re && (id_rR1 != 5'd0) &&
                              s1_m2_producer && (id_rR1 == s1_m2_wR);
    wire id_r1_s1_wb_match = id_rR1_re && (id_rR1 != 5'd0) &&
                              s1_wb_producer && (id_rR1 == s1_wb_wR);
    wire id_r2_s1_of_match = id_rR2_re && (id_rR2 != 5'd0) &&
                              s1_of_producer && (id_rR2 == s1_of_wR);
    wire id_r2_s1_ex_match = id_rR2_re && (id_rR2 != 5'd0) &&
                              s1_ex_producer && (id_rR2 == s1_ex_wR);
    wire id_r2_s1_m1_match = id_rR2_re && (id_rR2 != 5'd0) &&
                              s1_m1_producer && (id_rR2 == s1_m1_wR);
    wire id_r2_s1_m2_match = id_rR2_re && (id_rR2 != 5'd0) &&
                              s1_m2_producer && (id_rR2 == s1_m2_wR);
    wire id_r2_s1_wb_match = id_rR2_re && (id_rR2 != 5'd0) &&
                              s1_wb_producer && (id_rR2 == s1_wb_wR);

    // Select the youngest producer across both lanes.  Pipeline stage order is
    // OF > EX > M1 > M2 > WB; within one bundle slot 1 is younger than slot 0
    // (same-bundle WAW is already forbidden, so the tie rule is defensive).
    // Select from the registered next-state dependency snapshot.  All live
    // destination comparisons now end at id_r*_writer_tag.D and cannot feed
    // ID2 stall, IBUF pop/head enables or lane-1 data selection in the same
    // cycle.  Within a stage slot 1 is younger than slot 0.
    wire id_r1_s1_of_sel = id_r1_writer_tag[8];
    wire id_r1_s1_ex_sel = id_r1_writer_tag[6] &&
                            !(|id_r1_writer_tag[8:7]);
    wire id_r1_s1_m1_sel = id_r1_writer_tag[4] &&
                            !(|id_r1_writer_tag[8:5]);
    wire id_r1_s1_m2_sel = id_r1_writer_tag[2] &&
                            !(|id_r1_writer_tag[8:3]);
    wire id_r1_s1_wb_sel = id_r1_writer_tag[0] &&
                            !(|id_r1_writer_tag[8:1]);
    wire id_r2_s1_of_sel = id_r2_writer_tag[8];
    wire id_r2_s1_ex_sel = id_r2_writer_tag[6] &&
                            !(|id_r2_writer_tag[8:7]);
    wire id_r2_s1_m1_sel = id_r2_writer_tag[4] &&
                            !(|id_r2_writer_tag[8:5]);
    wire id_r2_s1_m2_sel = id_r2_writer_tag[2] &&
                            !(|id_r2_writer_tag[8:3]);
    wire id_r2_s1_wb_sel = id_r2_writer_tag[0] &&
                            !(|id_r2_writer_tag[8:1]);

    wire id_r1_s1_ready = id_r1_s1_m1_sel || id_r1_s1_m2_sel ||
                           id_r1_s1_wb_sel;
    wire id_r2_s1_ready = id_r2_s1_m1_sel || id_r2_s1_m2_sel ||
                           id_r2_s1_wb_sel;
    wire [31:0] id_r1_s1_wd = id_r1_s1_m1_sel ? s1_m1_wd :
                               id_r1_s1_m2_sel ? s1_m2_wd : s1_wb_wd;
    wire [31:0] id_r2_s1_wd = id_r2_s1_m1_sel ? s1_m1_wd :
                               id_r2_s1_m2_sel ? s1_m2_wd : s1_wb_wd;
    wire [31:0] id_of_raw_rD1 = id_r1_s1_ready ?
                                 id_r1_s1_wd : id_real_rD1;
    wire [31:0] id_of_raw_rD2 = id_r2_s1_ready ?
                                 id_r2_s1_wd : id_real_rD2;
    wire [3:0] id_r1_dep_tag_to_of = id_r1_s1_ready ?
                                      4'b0000 : id_r1_dep_tag;
    wire [3:0] id_r2_dep_tag_to_of = id_r2_s1_ready ?
                                      4'b0000 : id_r2_dep_tag;

    // Branch/JIRL/system logic remains isolated from lane-1 result data and
    // waits through WB2 refresh.  Ordinary consumers wait only while their
    // youngest lane-1 producer is still in OF/EX.  Write the priority test in
    // absorbed form: tag[8] now reaches the final wait result directly instead
    // of reconverging through the lower-stage ready network.  This is a strict
    // Boolean identity for every possible nine-bit tag vector, not a false or
    // multicycle timing exception.
    wire id_r1_s1_late_priority = id_r1_writer_tag[4] ||
        (!id_r1_writer_tag[3] &&
         (id_r1_writer_tag[2] ||
          (!id_r1_writer_tag[1] && id_r1_writer_tag[0])));
    wire id_r2_s1_late_priority = id_r2_writer_tag[4] ||
        (!id_r2_writer_tag[3] &&
         (id_r2_writer_tag[2] ||
          (!id_r2_writer_tag[1] && id_r2_writer_tag[0])));
    wire id_r1_s1_wait = id_r1_writer_tag[8] ||
        (!id_r1_writer_tag[7] &&
         (id_r1_writer_tag[6] ||
          (id_control_consumer && !id_r1_writer_tag[5] &&
           id_r1_s1_late_priority)));
    wire id_r2_s1_wait = id_r2_writer_tag[8] ||
        (!id_r2_writer_tag[7] &&
         (id_r2_writer_tag[6] ||
          (id_control_consumer && !id_r2_writer_tag[5] &&
           id_r2_s1_late_priority)));
`ifndef SYNTHESIS
    wire id_r1_s1_wait_reference = id_r1_s1_of_sel ||
        id_r1_s1_ex_sel || (id_control_consumer && id_r1_s1_ready);
    wire id_r2_s1_wait_reference = id_r2_s1_of_sel ||
        id_r2_s1_ex_sel || (id_control_consumer && id_r2_s1_ready);
    always @(posedge cpu_clk) begin
        if (cpu_rstn &&
            ((id_r1_s1_wait !== id_r1_s1_wait_reference) ||
             (id_r2_s1_wait !== id_r2_s1_wait_reference)))
            $fatal(1, "absorbed lane-1 wait differs from priority reference");
    end
`endif
    wire slot0_lane1_wait = id_waiting &&
                            (id_r1_s1_wait || id_r2_s1_wait);

    // The younger candidate may pair only when its RF operands need no value
    // from an older slot-0 or slot-1 instruction.  Querying a registered
    // writer multiset cuts all live backend wR comparisons out of this path.
    wire s1_r1_old_pending = s1_dec_rR1_re && (s1_dec_rR1 != 5'd0) &&
        (pending_older_busy[s1_dec_rR1] ||
         (s0_of_producer && (s1_dec_rR1 == of_wR)) ||
         (s1_of_producer && (s1_dec_rR1 == s1_of_wR)));
    wire s1_r2_old_pending = s1_dec_rR2_re && (s1_dec_rR2 != 5'd0) &&
        (pending_older_busy[s1_dec_rR2] ||
         (s0_of_producer && (s1_dec_rR2 == of_wR)) ||
         (s1_of_producer && (s1_dec_rR2 == s1_of_wR)));

`ifndef SYNTHESIS
    // Simulation-only reference for a cycle-exact equivalence proof.  These
    // comparisons must never return to the synthesized pair path.
    wire [8:0] legacy_id_r1_writer_tag = {
        id_r1_s1_of_match, id_r1_of_match,
        id_r1_s1_ex_match, id_r1_ex_match,
        id_r1_s1_m1_match, id_r1_m1_match,
        id_r1_s1_m2_match, id_r1_m2_match,
        id_r1_s1_wb_match
    };
    wire [8:0] legacy_id_r2_writer_tag = {
        id_r2_s1_of_match, id_r2_of_match,
        id_r2_s1_ex_match, id_r2_ex_match,
        id_r2_s1_m1_match, id_r2_m1_match,
        id_r2_s1_m2_match, id_r2_m2_match,
        id_r2_s1_wb_match
    };
    wire legacy_s1_r1_old_slot0 = s1_dec_rR1_re &&
        (s1_dec_rR1 != 5'd0) &&
        ((of_valid && of_rf_we && (of_wR != 5'd0) &&
          (s1_dec_rR1 == of_wR)) ||
         (ex_valid && ex_rf_we && (ex_wR != 5'd0) &&
          (s1_dec_rR1 == ex_wR)) ||
         (x2_valid && x2_rf_we && (x2_wR != 5'd0) &&
          (s1_dec_rR1 == x2_wR)) ||
         (mem_valid && mem_rf_we && (mem_wR != 5'd0) &&
          (s1_dec_rR1 == mem_wR)));
    wire legacy_s1_r2_old_slot0 = s1_dec_rR2_re &&
        (s1_dec_rR2 != 5'd0) &&
        ((of_valid && of_rf_we && (of_wR != 5'd0) &&
          (s1_dec_rR2 == of_wR)) ||
         (ex_valid && ex_rf_we && (ex_wR != 5'd0) &&
          (s1_dec_rR2 == ex_wR)) ||
         (x2_valid && x2_rf_we && (x2_wR != 5'd0) &&
          (s1_dec_rR2 == x2_wR)) ||
         (mem_valid && mem_rf_we && (mem_wR != 5'd0) &&
          (s1_dec_rR2 == mem_wR)));
    wire legacy_s1_r1_old_slot1 = s1_dec_rR1_re &&
        (s1_dec_rR1 != 5'd0) &&
        ((s1_of_producer && (s1_dec_rR1 == s1_of_wR)) ||
         (s1_ex_producer && (s1_dec_rR1 == s1_ex_wR)) ||
         (s1_m1_producer && (s1_dec_rR1 == s1_m1_wR)) ||
         (s1_m2_producer && (s1_dec_rR1 == s1_m2_wR)));
    wire legacy_s1_r2_old_slot1 = s1_dec_rR2_re &&
        (s1_dec_rR2 != 5'd0) &&
        ((s1_of_producer && (s1_dec_rR2 == s1_of_wR)) ||
         (s1_ex_producer && (s1_dec_rR2 == s1_ex_wR)) ||
         (s1_m1_producer && (s1_dec_rR2 == s1_m1_wR)) ||
         (s1_m2_producer && (s1_dec_rR2 == s1_m2_wR)));
    wire legacy_s1_old_producer_block =
        legacy_s1_r1_old_slot0 | legacy_s1_r2_old_slot0 |
        legacy_s1_r1_old_slot1 | legacy_s1_r2_old_slot1;
`endif

    wire pair_raw = id_rf_we && (id_wR != 5'd0) &&
        ((s1_dec_rR1_re && (s1_dec_rR1 == id_wR)) ||
         (s1_dec_rR2_re && (s1_dec_rR2 == id_wR)));
    wire pair_waw = id_rf_we && (id_wR != 5'd0) &&
                    s1_dec_writes_gpr && (id_wR == s1_dec_wR);
    // With a one-word fetch port, a pair is profitable only if the already
    // buffered third instruction C can issue behind it.  Until lane-1 gains a
    // registered result bypass, conservatively reject B(slot1) whenever any
    // architectural register field of C names B's destination.  LoongArch GPR
    // sources are encoded in rj/rk/rd; treating an unused/destination field as
    // a source creates only a harmless false rejection and cannot miss a RAW.
    wire pair_next_raw = ibuf_raw_from_prev2;
`ifndef SYNTHESIS
    // Retain the former live comparison only as a simulation oracle.  The
    // synthesized pair/pop/head path consumes the registered one-bit IBUF
    // sidecar above, while this proves that the accepted pair set is unchanged.
    wire pair_next_raw_reference = s1_dec_writes_gpr &&
        (((ibuf_inst2[ 9: 5] == s1_dec_wR) && (s1_dec_wR != 5'd0)) ||
         ((ibuf_inst2[14:10] == s1_dec_wR) && (s1_dec_wR != 5'd0)) ||
         ((ibuf_inst2[ 4: 0] == s1_dec_wR) && (s1_dec_wR != 5'd0)));
`endif
    wire s1_old_producer_block = s1_r1_old_pending |
                                 s1_r2_old_pending;

    wire id_issue_block = id_system_issue_wait | system_pipe_busy |
                          branch_resolve_conflict |
                          slot0_lane1_wait;
    // One local block term owns all ID2-boundary handshakes.  The former
    // expressions separately rebuilt OF allowin, ID2 stall and refill, which
    // made a late OF operand_wait reconverge through several equivalent mux
    // levels before reaching IBUF and slot-1 payload enables.  This term is
    // exactly !of_direct_allowin | id_issue_block from the former equations.
    wire id_boundary_block = id_issue_block |
        (!front_redirect_from_of_r && of_valid &&
         (early_load_hold || of_operand_wait));
    wire id2_stall = id_waiting && id_boundary_block;
    wire id_to_of_valid = id_waiting && !pl_suspend &&
                          !id_boundary_block;
    // Positive accepted-refill event.  The outer !front_redirect_valid
    // already excludes front_redirect_from_of_r, so this is cycle-identical
    // to the prior direct equation while sharing only the shallow block term.
    wire id_refill_fire = ibuf_valid && !front_redirect_valid &&
        !pl_suspend &&
        (!id_waiting || !id_boundary_block);
    // A+B may issue together only when C is already resident behind B.  The
    // fetch path supplies one instruction per cycle; pairing with only B would
    // empty ID2 on the same edge and merely move the saved issue cycle into a
    // refill bubble.  Requiring the registered second head makes every pair a
    // real backlog-draining event: B enters slot 1 while C refills slot 0.
    wire pair_accept = ibuf_valid && ibuf_valid2 && s1_dec_eligible &&
                       id_pair_class_ok && !ibuf_pred_taken &&
                       ibuf_seq_from_prev &&
                       !pair_raw && !pair_waw && !pair_next_raw &&
                       !s1_old_producer_block;
    // The candidate decision is independent of the downstream ID2/OF
    // handshake and may therefore drive only final B/C payload selection and
    // the raw pop2 request.  Architectural issue remains pop-gated below.
    (* max_fanout = 32 *) wire pair_candidate = id_waiting && pair_accept;
    // Under pair_candidate, both ID2 and the IBUF head are valid.  Absorb
    // those implications instead of routing the decision through the shared
    // refill/pop tree before broadcasting it to the slot-1 payload enables.
    wire pair_issue_direct = pair_candidate && !front_redirect_valid &&
                             !pl_suspend && !id_boundary_block;
    assign pair_issue = pair_issue_direct;

    // ------------------------------------------------------------------
    // Exact next-state dependency snapshot for the resident ID2 payload.
    // ------------------------------------------------------------------
    // Each descriptor below is the writer which will occupy that architectural
    // stage immediately after the upcoming edge.  The tag registers query
    // these next descriptors on the same edge, so a producer moving EX->M1
    // releases an ordinary consumer on exactly the same cycle as the former
    // live comparisons.  WAW is preserved because every stage has its own
    // match bit; no set/clear bitmap collapses multiple writers.
    wire s0_of_prod_next = front_redirect_from_of_r ? 1'b0 :
        id_to_of_valid ? (id_rf_we && (id_wR != 5'd0)) :
        of_fire ? 1'b0 : s0_of_producer;
    wire [4:0] s0_of_dst_next = id_to_of_valid ? id_wR : of_wR;
    wire s0_ex_prod_next = (pl_suspend || early_load_hold) ?
        (ex_valid && ex_rf_we && (ex_wR != 5'd0)) :
        (of_fire && of_rf_we && (of_wR != 5'd0));
    wire [4:0] s0_ex_dst_next =
        (pl_suspend || early_load_hold) ? ex_wR : of_wR;
    wire s0_m1_prod_next = pl_suspend ?
        (x2_valid && x2_rf_we && (x2_wR != 5'd0)) :
        (ex_valid && !early_load_hold && ex_rf_we && (ex_wR != 5'd0));
    wire [4:0] s0_m1_dst_next = pl_suspend ? x2_wR : ex_wR;
    wire s0_m2_prod_next = pl_suspend ?
        (mem_valid && mem_rf_we && (mem_wR != 5'd0)) :
        (x2_valid && x2_rf_we && !x2_ldst_unalign &&
         (x2_wR != 5'd0));
    wire [4:0] s0_m2_dst_next = pl_suspend ? mem_wR : x2_wR;

    // The no-pair form is also the exact S1-OF state for a head0 refill and
    // for a resident ID2 hold.  Keeping it separate lets both B/C tag sets be
    // built in parallel; the late pair decision then controls only one final
    // 2:1 tag mux.
    wire s1_of_prod_next_no_pair = front_redirect_from_of_r ? 1'b0 :
        of_fire ? 1'b0 : s1_of_producer;
    wire [4:0] s1_of_dst_next_no_pair = s1_of_wR;
    wire s1_of_prod_next = front_redirect_from_of_r ? 1'b0 :
        pair_issue ? (s1_dec_writes_gpr && (s1_dec_wR != 5'd0)) :
        s1_of_prod_next_no_pair;
    wire [4:0] s1_of_dst_next = pair_issue ?
                                  s1_dec_wR : s1_of_dst_next_no_pair;
    wire s1_ex_prod_next = (pl_suspend || early_load_hold) ?
        s1_ex_producer :
        (of_fire && s1_of_producer);
    wire [4:0] s1_ex_dst_next =
        (pl_suspend || early_load_hold) ? s1_ex_wR : s1_of_wR;
    wire s1_m1_prod_next = pl_suspend ? s1_m1_producer :
        (s1_ex_producer && !early_load_hold);
    wire [4:0] s1_m1_dst_next = pl_suspend ? s1_m1_wR : s1_ex_wR;
    wire s1_m2_prod_next = pl_suspend ? s1_m2_producer : s1_m1_producer;
    wire [4:0] s1_m2_dst_next = pl_suspend ? s1_m2_wR : s1_m1_wR;
    wire s1_wb_prod_next = !pl_suspend && s1_m2_producer;
    wire [4:0] s1_wb_dst_next = s1_m2_wR;

    function [8:0] make_writer_tag_next;
        input [4:0] src;
        input       src_re;
        input       tag_s1_of_prod;
        input [4:0] tag_s1_of_dst;
        begin
            make_writer_tag_next[8] = src_re && (src != 5'd0) &&
                                      tag_s1_of_prod &&
                                      (src == tag_s1_of_dst);
            make_writer_tag_next[7] = src_re && (src != 5'd0) &&
                                      s0_of_prod_next &&
                                      (src == s0_of_dst_next);
            make_writer_tag_next[6] = src_re && (src != 5'd0) &&
                                      s1_ex_prod_next &&
                                      (src == s1_ex_dst_next);
            make_writer_tag_next[5] = src_re && (src != 5'd0) &&
                                      s0_ex_prod_next &&
                                      (src == s0_ex_dst_next);
            make_writer_tag_next[4] = src_re && (src != 5'd0) &&
                                      s1_m1_prod_next &&
                                      (src == s1_m1_dst_next);
            make_writer_tag_next[3] = src_re && (src != 5'd0) &&
                                      s0_m1_prod_next &&
                                      (src == s0_m1_dst_next);
            make_writer_tag_next[2] = src_re && (src != 5'd0) &&
                                      s1_m2_prod_next &&
                                      (src == s1_m2_dst_next);
            make_writer_tag_next[1] = src_re && (src != 5'd0) &&
                                      s0_m2_prod_next &&
                                      (src == s0_m2_dst_next);
            make_writer_tag_next[0] = src_re && (src != 5'd0) &&
                                      s1_wb_prod_next &&
                                      (src == s1_wb_dst_next);
        end
    endfunction

    function src_writer_match;
        input [4:0] src;
        input       src_re;
        input       producer;
        input [4:0] dst;
        begin
            src_writer_match = src_re && (src != 5'd0) && producer &&
                               (dst != 5'd0) && (src == dst);
        end
    endfunction

    // A held resident ID2 payload keeps the same source indices, so its tag
    // vector can advance with the producer stages directly.  Re-comparing the
    // saved source against nine next descriptors made OF backpressure select
    // a large compare network on every tag D input.  This shift is exactly the
    // same next-state transform, including early-load hold, unaligned cancel
    // and the transient S1-WB refresh bit.
    function [8:0] advance_resident_writer_tag;
        input [8:0] current_tag;
        begin
            advance_resident_writer_tag[8] =
                front_redirect_from_of_r ? 1'b0 :
                (of_fire ? 1'b0 : current_tag[8]);
            advance_resident_writer_tag[7] =
                front_redirect_from_of_r ? 1'b0 :
                (of_fire ? 1'b0 : current_tag[7]);
            advance_resident_writer_tag[6] =
                (pl_suspend || early_load_hold) ? current_tag[6] :
                (of_fire ? current_tag[8] : 1'b0);
            advance_resident_writer_tag[5] =
                (pl_suspend || early_load_hold) ? current_tag[5] :
                (of_fire ? current_tag[7] : 1'b0);
            advance_resident_writer_tag[4] = pl_suspend ? current_tag[4] :
                (early_load_hold ? 1'b0 : current_tag[6]);
            advance_resident_writer_tag[3] = pl_suspend ? current_tag[3] :
                (early_load_hold ? 1'b0 : current_tag[5]);
            advance_resident_writer_tag[2] =
                pl_suspend ? current_tag[2] : current_tag[4];
            advance_resident_writer_tag[1] = pl_suspend ? current_tag[1] :
                (x2_ldst_unalign ? 1'b0 : current_tag[3]);
            advance_resident_writer_tag[0] =
                pl_suspend ? 1'b0 : current_tag[2];
        end
    endfunction

    wire capture1_s1_of_prod = s1_dec_writes_gpr &&
                               (s1_dec_wR != 5'd0);
    wire [8:0] capture0_r1_writer_tag_next = make_writer_tag_next(
        id_capture0_rR1, id_capture0_rR1_re,
        s1_of_prod_next_no_pair, s1_of_dst_next_no_pair);
    wire [8:0] capture0_r2_writer_tag_next = make_writer_tag_next(
        id_capture0_rR2, id_capture0_rR2_re,
        s1_of_prod_next_no_pair, s1_of_dst_next_no_pair);
    wire [8:0] capture1_r1_writer_tag_next = make_writer_tag_next(
        id_capture1_rR1, id_capture1_rR1_re,
        capture1_s1_of_prod, s1_dec_wR);
    wire [8:0] capture1_r2_writer_tag_next = make_writer_tag_next(
        id_capture1_rR2, id_capture1_rR2_re,
        capture1_s1_of_prod, s1_dec_wR);
    wire [8:0] capture_r1_writer_tag_next_generic = pair_candidate ?
        capture1_r1_writer_tag_next : capture0_r1_writer_tag_next;
    wire [8:0] capture_r2_writer_tag_next_generic = pair_candidate ?
        capture1_r2_writer_tag_next : capture0_r2_writer_tag_next;

    // Refill reachability gives the two OF-stage tag bits a much shallower
    // exact equation than the generic next-descriptor network:
    //   * resident ID2 + refill: the old ID2 payload becomes S0-OF;
    //   * empty ID2 + refill: only a non-firing old OF payload survives;
    //   * paired refill: B becomes S1-OF and C is captured into ID2.
    // Compute head0/head1 comparisons in parallel, then select the result, so
    // OF-ready does not reconverge through destination and source muxes.
    wire cap0_r1_id_match = src_writer_match(
        id_capture0_rR1, id_capture0_rR1_re, id_rf_we, id_wR);
    wire cap1_r1_id_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re, id_rf_we, id_wR);
    wire cap0_r2_id_match = src_writer_match(
        id_capture0_rR2, id_capture0_rR2_re, id_rf_we, id_wR);
    wire cap1_r2_id_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re, id_rf_we, id_wR);
    wire cap_r1_id_match = pair_candidate ?
                           cap1_r1_id_match : cap0_r1_id_match;
    wire cap_r2_id_match = pair_candidate ?
                           cap1_r2_id_match : cap0_r2_id_match;

    wire cap0_r1_s0of_match = src_writer_match(
        id_capture0_rR1, id_capture0_rR1_re, s0_of_producer, of_wR);
    wire cap0_r2_s0of_match = src_writer_match(
        id_capture0_rR2, id_capture0_rR2_re, s0_of_producer, of_wR);
    wire cap1_r1_pairb_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re,
        s1_dec_writes_gpr, s1_dec_wR);
    wire cap1_r2_pairb_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re,
        s1_dec_writes_gpr, s1_dec_wR);
    wire cap0_r1_s1of_match = src_writer_match(
        id_capture0_rR1, id_capture0_rR1_re,
        s1_of_producer, s1_of_wR);
    wire cap0_r2_s1of_match = src_writer_match(
        id_capture0_rR2, id_capture0_rR2_re,
        s1_of_producer, s1_of_wR);

    // On an accepted refill pl_suspend is known low.  Therefore the two EX
    // writer descriptors have only two reachable sources: a locally held EX
    // payload during early_load_hold, or the registered OF payload admitted
    // by of_fire.  Compare head0/head1 against both candidates in parallel;
    // this removes generic next-descriptor and pair-state logic from tag[6:5]
    // after the late OF-ready decision.
    wire cap1_r1_s0of_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re, s0_of_producer, of_wR);
    wire cap1_r2_s0of_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re, s0_of_producer, of_wR);
    wire cap1_r1_s1of_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re,
        s1_of_producer, s1_of_wR);
    wire cap1_r2_s1of_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re,
        s1_of_producer, s1_of_wR);
    wire cap0_r1_s0ex_match = src_writer_match(
        id_capture0_rR1, id_capture0_rR1_re,
        ex_valid && ex_rf_we, ex_wR);
    wire cap0_r2_s0ex_match = src_writer_match(
        id_capture0_rR2, id_capture0_rR2_re,
        ex_valid && ex_rf_we, ex_wR);
    wire cap0_r1_s1ex_match = src_writer_match(
        id_capture0_rR1, id_capture0_rR1_re,
        s1_ex_producer, s1_ex_wR);
    wire cap0_r2_s1ex_match = src_writer_match(
        id_capture0_rR2, id_capture0_rR2_re,
        s1_ex_producer, s1_ex_wR);
    wire cap1_r1_s0ex_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re,
        ex_valid && ex_rf_we, ex_wR);
    wire cap1_r2_s0ex_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re,
        ex_valid && ex_rf_we, ex_wR);
    wire cap1_r1_s1ex_match = src_writer_match(
        id_capture1_rR1, id_capture1_rR1_re,
        s1_ex_producer, s1_ex_wR);
    wire cap1_r2_s1ex_match = src_writer_match(
        id_capture1_rR2, id_capture1_rR2_re,
        s1_ex_producer, s1_ex_wR);

    wire cap_r1_s0of_match = pair_candidate ?
        cap1_r1_s0of_match : cap0_r1_s0of_match;
    wire cap_r2_s0of_match = pair_candidate ?
        cap1_r2_s0of_match : cap0_r2_s0of_match;
    wire cap_r1_s1of_match = pair_candidate ?
        cap1_r1_s1of_match : cap0_r1_s1of_match;
    wire cap_r2_s1of_match = pair_candidate ?
        cap1_r2_s1of_match : cap0_r2_s1of_match;
    wire cap_r1_s0ex_match = pair_candidate ?
        cap1_r1_s0ex_match : cap0_r1_s0ex_match;
    wire cap_r2_s0ex_match = pair_candidate ?
        cap1_r2_s0ex_match : cap0_r2_s0ex_match;
    wire cap_r1_s1ex_match = pair_candidate ?
        cap1_r1_s1ex_match : cap0_r1_s1ex_match;
    wire cap_r2_s1ex_match = pair_candidate ?
        cap1_r2_s1ex_match : cap0_r2_s1ex_match;

    wire capture_r1_tag7_fast = id_waiting ? cap_r1_id_match :
                                       (!of_fire && cap0_r1_s0of_match);
    wire capture_r2_tag7_fast = id_waiting ? cap_r2_id_match :
                                       (!of_fire && cap0_r2_s0of_match);
    wire capture_r1_tag8_fast = pair_candidate ? cap1_r1_pairb_match :
                                       (!of_fire && cap0_r1_s1of_match);
    wire capture_r2_tag8_fast = pair_candidate ? cap1_r2_pairb_match :
                                       (!of_fire && cap0_r2_s1of_match);
    wire capture_r1_tag6_fast = early_load_hold ?
        cap_r1_s1ex_match : (of_fire && cap_r1_s1of_match);
    wire capture_r2_tag6_fast = early_load_hold ?
        cap_r2_s1ex_match : (of_fire && cap_r2_s1of_match);
    wire capture_r1_tag5_fast = early_load_hold ?
        cap_r1_s0ex_match : (of_fire && cap_r1_s0of_match);
    wire capture_r2_tag5_fast = early_load_hold ?
        cap_r2_s0ex_match : (of_fire && cap_r2_s0of_match);
    wire [8:0] capture_r1_writer_tag_next = {
        capture_r1_tag8_fast, capture_r1_tag7_fast,
        capture_r1_tag6_fast, capture_r1_tag5_fast,
        capture_r1_writer_tag_next_generic[4:0]
    };
    wire [8:0] capture_r2_writer_tag_next = {
        capture_r2_tag8_fast, capture_r2_tag7_fast,
        capture_r2_tag6_fast, capture_r2_tag5_fast,
        capture_r2_writer_tag_next_generic[4:0]
    };
    wire [8:0] resident_r1_writer_tag_next =
        advance_resident_writer_tag(id_r1_writer_tag);
    wire [8:0] resident_r2_writer_tag_next =
        advance_resident_writer_tag(id_r2_writer_tag);

    // Absorb the refill/resident selection into the two EX tag bits.  In the
    // early-hold branch the next EX descriptor is the current EX register; in
    // the of_fire branch it is the current OF register.  The branch-local
    // refill predicates are exact reductions of id_refill_fire under those
    // guards, so operand_wait no longer reconverges through the generic stage
    // descriptor and a second outer mux on tag[6:5].
    wire writer_tag_refill_early = ibuf_valid &&
        !front_redirect_valid &&
        (!id_waiting || (!id_issue_block && !of_valid));
    wire writer_tag_refill_of_fire = ibuf_valid &&
        !front_redirect_valid &&
        (!id_waiting || !id_issue_block);
    // Complete the no-pair and pair next-state cones independently.  A late
    // pair decision used to select the source match first and then traverse
    // the early-load/OF/refill control tree, placing five LUTs after the
    // already expensive pair hazard check.  Both variants below are exact
    // expansions of that equation; KEEP makes the only pair-dependent logic a
    // final one-bit mux at each tag flop.
    (* KEEP = "true" *) wire r1_tag6_no_pair = pl_suspend ?
        id_r1_writer_tag[6] : early_load_hold ?
        (writer_tag_refill_early ? cap0_r1_s1ex_match :
                                   id_r1_writer_tag[6]) : of_fire ?
        (writer_tag_refill_of_fire ? cap0_r1_s1of_match :
                                     id_r1_writer_tag[8]) : 1'b0;
    (* KEEP = "true" *) wire r1_tag6_pair = pl_suspend ?
        id_r1_writer_tag[6] : early_load_hold ?
        (writer_tag_refill_early ? cap1_r1_s1ex_match :
                                   id_r1_writer_tag[6]) : of_fire ?
        (writer_tag_refill_of_fire ? cap1_r1_s1of_match :
                                     id_r1_writer_tag[8]) : 1'b0;
    (* KEEP = "true" *) wire r2_tag6_no_pair = pl_suspend ?
        id_r2_writer_tag[6] : early_load_hold ?
        (writer_tag_refill_early ? cap0_r2_s1ex_match :
                                   id_r2_writer_tag[6]) : of_fire ?
        (writer_tag_refill_of_fire ? cap0_r2_s1of_match :
                                     id_r2_writer_tag[8]) : 1'b0;
    (* KEEP = "true" *) wire r2_tag6_pair = pl_suspend ?
        id_r2_writer_tag[6] : early_load_hold ?
        (writer_tag_refill_early ? cap1_r2_s1ex_match :
                                   id_r2_writer_tag[6]) : of_fire ?
        (writer_tag_refill_of_fire ? cap1_r2_s1of_match :
                                     id_r2_writer_tag[8]) : 1'b0;
    (* KEEP = "true" *) wire r1_tag5_no_pair = pl_suspend ?
        id_r1_writer_tag[5] : early_load_hold ?
        (writer_tag_refill_early ? cap0_r1_s0ex_match :
                                   id_r1_writer_tag[5]) : of_fire ?
        (writer_tag_refill_of_fire ? cap0_r1_s0of_match :
                                     id_r1_writer_tag[7]) : 1'b0;
    (* KEEP = "true" *) wire r1_tag5_pair = pl_suspend ?
        id_r1_writer_tag[5] : early_load_hold ?
        (writer_tag_refill_early ? cap1_r1_s0ex_match :
                                   id_r1_writer_tag[5]) : of_fire ?
        (writer_tag_refill_of_fire ? cap1_r1_s0of_match :
                                     id_r1_writer_tag[7]) : 1'b0;
    (* KEEP = "true" *) wire r2_tag5_no_pair = pl_suspend ?
        id_r2_writer_tag[5] : early_load_hold ?
        (writer_tag_refill_early ? cap0_r2_s0ex_match :
                                   id_r2_writer_tag[5]) : of_fire ?
        (writer_tag_refill_of_fire ? cap0_r2_s0of_match :
                                     id_r2_writer_tag[7]) : 1'b0;
    (* KEEP = "true" *) wire r2_tag5_pair = pl_suspend ?
        id_r2_writer_tag[5] : early_load_hold ?
        (writer_tag_refill_early ? cap1_r2_s0ex_match :
                                   id_r2_writer_tag[5]) : of_fire ?
        (writer_tag_refill_of_fire ? cap1_r2_s0of_match :
                                     id_r2_writer_tag[7]) : 1'b0;

    wire r1_writer_tag6_next_direct = pair_candidate ?
        r1_tag6_pair : r1_tag6_no_pair;
    wire r2_writer_tag6_next_direct = pair_candidate ?
        r2_tag6_pair : r2_tag6_no_pair;
    wire r1_writer_tag5_next_direct = pair_candidate ?
        r1_tag5_pair : r1_tag5_no_pair;
    wire r2_writer_tag5_next_direct = pair_candidate ?
        r2_tag5_pair : r2_tag5_no_pair;

    wire [8:0] r1_writer_tag_selected_next = id_refill_fire ?
        capture_r1_writer_tag_next : resident_r1_writer_tag_next;
    wire [8:0] r2_writer_tag_selected_next = id_refill_fire ?
        capture_r2_writer_tag_next : resident_r2_writer_tag_next;
    wire [8:0] r1_writer_tag_d = {
        r1_writer_tag_selected_next[8:7],
        r1_writer_tag6_next_direct, r1_writer_tag5_next_direct,
        r1_writer_tag_selected_next[4:0]
    };
    wire [8:0] r2_writer_tag_d = {
        r2_writer_tag_selected_next[8:7],
        r2_writer_tag6_next_direct, r2_writer_tag5_next_direct,
        r2_writer_tag_selected_next[4:0]
    };
`ifndef SYNTHESIS
    wire [8:0] resident_r1_writer_tag_next_reference =
        make_writer_tag_next(id_rR1, id_rR1_re,
                             s1_of_prod_next_no_pair,
                             s1_of_dst_next_no_pair);
    wire [8:0] resident_r2_writer_tag_next_reference =
        make_writer_tag_next(id_rR2, id_rR2_re,
                             s1_of_prod_next_no_pair,
                             s1_of_dst_next_no_pair);
    wire r1_writer_tag6_next_reference = id_refill_fire ?
        capture_r1_writer_tag_next_generic[6] :
        resident_r1_writer_tag_next[6];
    wire r1_writer_tag5_next_reference = id_refill_fire ?
        capture_r1_writer_tag_next_generic[5] :
        resident_r1_writer_tag_next[5];
    wire r2_writer_tag6_next_reference = id_refill_fire ?
        capture_r2_writer_tag_next_generic[6] :
        resident_r2_writer_tag_next[6];
    wire r2_writer_tag5_next_reference = id_refill_fire ?
        capture_r2_writer_tag_next_generic[5] :
        resident_r2_writer_tag_next[5];
`endif

    // The tag vector is observable only while ID2 contains a payload.  If ID2
    // is refilled, capture the incoming payload's exact next-stage matches;
    // otherwise advance the old vector with the producer stages.  Advancing a
    // stale vector while ID2 is empty is harmless, because the first refill
    // overwrites every bit before valid is asserted.  This removes the former
    // `id_waiting ? advance : 0` tail.  Vivado mapped that unobservable clear
    // onto the FDRE R pins, extending OF operand-ready through a dynamic reset
    // network on thirteen writer-tag flops.
    always @(posedge cpu_clk) begin
        if (!cpu_rstn) begin
            id_r1_writer_tag <= 9'b0;
            id_r2_writer_tag <= 9'b0;
        end else begin
            id_r1_writer_tag <= r1_writer_tag_d;
            id_r2_writer_tag <= r2_writer_tag_d;
        end
    end

    // Rebuild each older-busy bit from the exact next contents of the six
    // EX/M1/M2 writer slots.  WAWs are naturally safe because this is a union,
    // and pair admission cannot feed this D cone: its new producer remains in
    // OF and is observed directly from the registered S1-OF descriptor on the
    // following cycle.
    genvar pending_g;
    generate
        for (pending_g = 0; pending_g < 32;
             pending_g = pending_g + 1) begin : g_pending_writer
            localparam [4:0] PENDING_IDX = pending_g;
            wire busy_next_g =
                (s0_ex_prod_next && (s0_ex_dst_next == PENDING_IDX)) ||
                (s0_m1_prod_next && (s0_m1_dst_next == PENDING_IDX)) ||
                (s0_m2_prod_next && (s0_m2_dst_next == PENDING_IDX)) ||
                (s1_ex_prod_next && (s1_ex_dst_next == PENDING_IDX)) ||
                (s1_m1_prod_next && (s1_m1_dst_next == PENDING_IDX)) ||
                (s1_m2_prod_next && (s1_m2_dst_next == PENDING_IDX));

            always @(posedge cpu_clk) begin
                if (!cpu_rstn)
                    pending_older_busy[pending_g] <= 1'b0;
                else
                    pending_older_busy[pending_g] <= busy_next_g;
            end
        end
    endgenerate
`ifndef SYNTHESIS
    function [3:0] live_older_writer_count;
        input [4:0] idx;
        begin
            live_older_writer_count = 4'd0;
            live_older_writer_count = live_older_writer_count +
                (ex_valid && ex_rf_we && (ex_wR != 5'd0) &&
                 (ex_wR == idx));
            live_older_writer_count = live_older_writer_count +
                (x2_valid && x2_rf_we && (x2_wR != 5'd0) &&
                 (x2_wR == idx));
            live_older_writer_count = live_older_writer_count +
                (mem_valid && mem_rf_we && (mem_wR != 5'd0) &&
                 (mem_wR == idx));
            live_older_writer_count = live_older_writer_count +
                (s1_ex_producer && (s1_ex_wR == idx));
            live_older_writer_count = live_older_writer_count +
                (s1_m1_producer && (s1_m1_wR == idx));
            live_older_writer_count = live_older_writer_count +
                (s1_m2_producer && (s1_m2_wR == idx));
        end
    endfunction

    integer scoreboard_check_i;
    wire id2_stall_legacy = id_waiting &&
                            (!of_allowin | id_issue_block);
    wire ibuf_pop_legacy = ibuf_valid & !pl_suspend &
                           !front_redirect_valid & !id2_stall_legacy;
    wire pair_issue_legacy = id_to_of_valid && pair_accept && ibuf_pop;
    wire pair_accept_reference =
        ibuf_valid && ibuf_valid2 && s1_dec_eligible &&
        !id_is_br_jmp && !id_is_system &&
        !id_pred_taken && !ibuf_pred_taken &&
        ibuf_seq_from_prev &&
        !pair_raw && !pair_waw && !pair_next_raw_reference &&
        !s1_old_producer_block;
    wire slot0_lane1_wait_reference = id_waiting &&
        (id_r1_s1_of_sel || id_r1_s1_ex_sel ||
         ((id_is_br_jmp || id_is_system) && id_r1_s1_ready) ||
         id_r2_s1_of_sel || id_r2_s1_ex_sel ||
         ((id_is_br_jmp || id_is_system) && id_r2_s1_ready));
    wire id_issue_block_reference =
        (id_is_system &&
         (!id_system_checked_r || id_system_data_wait_r)) |
        system_pipe_busy |
        (id_is_system && store_pipeline_pending) |
        branch_resolve_conflict |
        slot0_lane1_wait_reference;
    always @(posedge cpu_clk) begin
        if (cpu_rstn) begin
            for (scoreboard_check_i = 0; scoreboard_check_i < 32;
                 scoreboard_check_i = scoreboard_check_i + 1) begin
                if (pending_older_busy[scoreboard_check_i] !==
                    (live_older_writer_count(scoreboard_check_i) != 4'd0))
                    $fatal(1, "pending-older bitmap differs from live stages");
            end
        end
        if (cpu_rstn && (id_to_of_valid !== id_valid))
            $fatal(1, "direct ID2->OF handshake differs from legacy handshake");
        if (cpu_rstn && !pl_suspend &&
            (id2_stall !== id2_stall_legacy))
            $fatal(1, "local ID2 stall differs from legacy observable stall");
        if (cpu_rstn && (id_refill_fire !== ibuf_pop_legacy))
            $fatal(1, "positive ID refill differs from legacy IBUF pop");
        if (cpu_rstn && (pair_issue !== pair_issue_legacy))
            $fatal(1, "pair candidate/fire changed accepted pair set");
        if (cpu_rstn && id_waiting &&
            (pair_accept !== pair_accept_reference))
            $fatal(1, "registered pair class changed pair acceptance");
        if (cpu_rstn && ibuf_valid2 &&
            (pair_next_raw !== pair_next_raw_reference))
            $fatal(1, "registered B-to-C RAW sidecar changed pair rejection");
        if (cpu_rstn && id_waiting &&
            (slot0_lane1_wait !== slot0_lane1_wait_reference))
            $fatal(1, "registered control class changed lane1 wait");
        if (cpu_rstn && id_waiting &&
            (id_issue_block !== id_issue_block_reference))
            $fatal(1, "registered system class changed issue blocking");
        if (cpu_rstn && id_refill_fire &&
            ((capture_r1_writer_tag_next !==
              capture_r1_writer_tag_next_generic) ||
             (capture_r2_writer_tag_next !==
              capture_r2_writer_tag_next_generic)))
            $fatal(1, "fast writer-tag OF capture differs from generic next descriptor");
        if (cpu_rstn &&
            ((r1_writer_tag6_next_direct !==
              r1_writer_tag6_next_reference) ||
             (r1_writer_tag5_next_direct !==
              r1_writer_tag5_next_reference) ||
             (r2_writer_tag6_next_direct !==
              r2_writer_tag6_next_reference) ||
             (r2_writer_tag5_next_direct !==
              r2_writer_tag5_next_reference)))
            $fatal(1, "absorbed writer-tag[6:5] next state differs from reference");
        if (cpu_rstn && id_refill_fire && (pl_suspend || id2_stall))
            $fatal(1, "writer-tag refill overlaps ID boundary hold");
        if (cpu_rstn && id_waiting &&
            (id_pc_plus4 !== (id_pc + 32'd4)))
            $fatal(1, "registered pairing PC successor mismatch");
        if (cpu_rstn && id_waiting && ibuf_valid &&
            (ibuf_seq_from_prev !== (ibuf_pc == id_pc_plus4)))
            $fatal(1, "IBUF sequential-PC sidecar differs from live comparison");
        if (cpu_rstn && ibuf_valid &&
            (s1_old_producer_block !== legacy_s1_old_producer_block))
            $fatal(1, "pending-writer scoreboard changed pair hazard block");
        // The lazy IBUF metadata mirror is architecturally observable only
        // when a second instruction exists and pairing is possible.  An
        // empty->one-entry transition intentionally clears it for one cycle
        // to keep ICache response data out of its D cone.
        if (cpu_rstn && ibuf_valid2 &&
            ({s1_dec_eligible, s1_meta_rR1, s1_dec_rR1_re,
              s1_meta_rR2, s1_dec_rR2_re, s1_meta_wR,
              s1_dec_writes_gpr} !==
             {s1_exec_eligible, s1_exec_rR1, s1_exec_rR1_re,
              s1_exec_rR2, s1_exec_rR2_re, s1_exec_wR,
              s1_exec_writes_gpr}))
            $fatal(1, "registered IBUF pair metadata differs from head decode");
        if (cpu_rstn && ibuf_valid &&
            ({s1_dec_rR1, s1_dec_rR2, s1_dec_wR} !==
             {s1_exec_rR1, s1_exec_rR2, s1_exec_wR}))
            $fatal(1, "direct pair register fields differ from head decode");
        if (cpu_rstn && id_waiting &&
            (id_r1_writer_tag !== legacy_id_r1_writer_tag))
            $fatal(1, "ID2 source1 writer tag differs from live stages");
        if (cpu_rstn && id_waiting &&
            (id_r2_writer_tag !== legacy_id_r2_writer_tag))
            $fatal(1, "ID2 source2 writer tag differs from live stages");
        // If the resident instruction issues while IBUF is empty, ID2 becomes
        // invalid and the stored tag value is unobservable.  Require exact
        // shift/recompute equivalence only for a payload that truly remains
        // resident across the edge.
        if (cpu_rstn && id_waiting && !id_refill_fire &&
            !id_to_of_valid &&
            ((resident_r1_writer_tag_next !==
              resident_r1_writer_tag_next_reference) ||
             (resident_r2_writer_tag_next !==
              resident_r2_writer_tag_next_reference))) begin
            $display("TAG_SHIFT_MISMATCH cur=%b/%b shift=%b/%b ref=%b/%b ps=%b elh=%b fire=%b redir=%b unalign=%b",
                     id_r1_writer_tag, id_r2_writer_tag,
                     resident_r1_writer_tag_next,
                     resident_r2_writer_tag_next,
                     resident_r1_writer_tag_next_reference,
                     resident_r2_writer_tag_next_reference,
                     pl_suspend, early_load_hold, of_fire,
                     front_redirect_from_of_r, x2_ldst_unalign);
            $fatal(1, "resident writer-tag shift differs from recompute");
        end
        if (cpu_rstn && pair_issue &&
            (!ibuf_valid2 || !ibuf_pop || front_redirect_valid ||
             !s1_dec_eligible || pair_raw || pair_waw || pair_next_raw ||
             s1_old_producer_block))
            $fatal(1, "restricted dual-issue acceptance invariant violated");
        if (cpu_rstn && pair_issue &&
            ((ibuf_pc != (id_pc + 32'd4)) ||
             !id_pair_class_ok || ibuf_pred_taken))
            $fatal(1, "restricted dual-issue control/PC invariant violated");
    end
`endif
    // On the cycle that the registered redirect is issued, ICache can still
    // present the hit belonging to the old inst_addr_r.  Discard it only when
    // its recorded request PC differs from the redirect target.  A self-loop
    // can already have the correct target response on this cycle and must not
    // lose the only event that keeps instruction fetch moving.
    // redirect_pending is registered.  Using if_redirect_req here would feed
    // IBUF can_fetch/pause_ifetch back into its own push decision and form a
    // combinational loop.
    assign ibuf_push = ifetch_valid & !front_redirect_valid;
    assign ibuf_pop  = id_refill_fire;
    // A pair is admitted only when A(ID2)+B(IBUF head) can consume C(head2)
    // into the normal ID1/ID2 boundary on the same edge.  A denied pair keeps
    // the original one-pop/one-capture schedule exactly.
    // pair_accept already requires valid2.  The pair decision controls only
    // IBUF state and the final registered-payload selector inside ID_stage;
    // it no longer selects an instruction ahead of decode/RF access.
    assign id_refill_from_second = pair_candidate;
    // InstBuffer qualifies this raw request with its accepted pop and valid2.
    assign ibuf_pop2 = pair_candidate;
    assign id_capture_valid = ibuf_pop;
    assign id_capture_pc = ibuf_pc;
    assign id_capture_inst = ibuf_inst;
    assign id_capture_pred_taken = ibuf_pred_taken;
    assign id_capture_pred_target = ibuf_pred_target;
    wire pause_ifetch = !ibuf_can_fetch;
    // ICache uses this independent credit to decide whether a hit can remain
    // in TAG_CHECK for the next request.  Unlike ifetch_rreq, it contains no
    // ICache hit/valid term, so the cache hit path cannot loop through IF/PC
    // control and back into the ICache state register.
    assign ifetch_chain_ready = ibuf_can_fetch;
    wire resume_ifetch_r;

    // Independent branches resolve in ID2; dependency-bearing branches resolve
    // from final operands in OF.  The older OF event always owns the update
    // port over a younger ID2 event.
    // Form the ID2 acceptance domain directly.  Rebuilding it through
    // id2_stall -> id_valid placed OF operand_wait in series with branch
    // compare, mispredict and both redirect/ID2-valid destination flops.
    // Under !front_redirect_from_of_r this is Boolean-identical to id_valid.
    wire id_accept_no_redirect = id_waiting && !pl_suspend &&
        !front_redirect_from_of_r && !id_boundary_block;
    wire id_resolve_valid = id_accept_no_redirect &&
                            (!id_is_br_jmp || !id_branch_deferred);
    wire resolve_from_of = of_deferred_resolve;
    wire resolve_valid = resolve_from_of ? of_deferred_resolve :
                                            id_resolve_valid;
    wire resolve_is_bj = resolve_from_of ? of_is_br_jmp : id_is_br_jmp;
    wire resolve_is_return = resolve_from_of ? of_is_return : id_is_return;
    wire [31:0] resolve_pc = resolve_from_of ? of_pc : id_pc;
    wire resolve_pred_taken = resolve_from_of ? of_pred_taken : id_pred_taken;
    wire [31:0] resolve_pred_target = resolve_from_of ?
                                      of_pred_target : id_pred_target;
    wire resolve_real_taken = resolve_from_of ? of_br_jmp_f : id_br_jmp_raw;
    wire [31:0] resolve_real_target = resolve_from_of ?
                                      of_taken_target : id_taken_target;
    wire id_taken_error_raw = (id_pred_taken && !id_is_br_jmp) ||
                              (id_is_br_jmp &&
                               (id_pred_taken != id_br_jmp_raw));
    wire id_target_error_raw = id_is_br_jmp && id_pred_taken &&
                               id_br_jmp_raw &&
                               (id_pred_target != id_taken_target);
    wire id_mispredict_candidate =
        (!id_is_br_jmp || !id_branch_deferred) &&
        (id_taken_error_raw || id_target_error_raw);
    wire id_early_mispredict = id_accept_no_redirect &&
                               id_mispredict_candidate;
`ifndef SYNTHESIS
    wire id_resolve_valid_reference = id_valid &&
        !front_redirect_from_of_r &&
        (!id_is_br_jmp || !id_branch_deferred);
    wire id_taken_error_reference =
        (id_pred_taken && !id_is_br_jmp) ||
        (id_is_br_jmp && (id_pred_taken != id_br_jmp_f));
    wire id_target_error_reference = id_is_br_jmp && id_pred_taken &&
        id_br_jmp_f && (id_pred_target != id_taken_target);
    wire id_early_mispredict_reference = id_resolve_valid_reference &&
        (id_taken_error_reference || id_target_error_reference);
    always @(posedge cpu_clk) begin
        if (cpu_rstn &&
            (id_resolve_valid !== id_resolve_valid_reference))
            $fatal(1, "direct ID2 resolve acceptance differs from legacy");
        if (cpu_rstn &&
            (id_early_mispredict !== id_early_mispredict_reference))
            $fatal(1, "raw ID2 mispredict candidate differs from legacy");
        if (cpu_rstn && id_valid &&
            (id_br_jmp_f !== id_br_jmp_raw))
            $fatal(1, "accepted ID2 branch outcome differs from raw result");
    end
`endif
    assign id2_mispredict = id_early_mispredict |
                            of_mispredict;
    wire id_issue_valid = id_valid && !of_mispredict;
    // The front end still sees only this registered event and target.  A late
    // OF correction kills the younger ID2 issue in the same cycle; IBUF/IF/
    // ICache are flushed by the registered pulse on the following cycle.
    always @(posedge cpu_clk) begin
        if (!cpu_rstn) begin
            front_redirect_id_valid_r        <= 1'b0;
            front_redirect_id_taken_r       <= 1'b0;
            front_redirect_target_pc_r      <= 32'b0;
            front_redirect_fallthrough_pc_r <= 32'b0;
        end else begin
            // ID2 and OF capture independent redirect events on the same edge.
            // The OF event is registered beside its comparator inside OF;
            // combining the two registered pulses here preserves the existing
            // redirect cycle without extending Load -> branch timing to a
            // top-level destination register.
            front_redirect_id_valid_r <= id_early_mispredict;
            // Register the decision and both redirect candidates separately.
            // This keeps the ID2 branch comparator out of the D input cone of
            // all 32 redirect-PC flops.  The front end only selects between
            // values that have already crossed this redirect boundary, so no
            // ID2 combinational signal can reach PC/IBUF/ICache control.
            front_redirect_id_taken_r       <= id_br_jmp_raw;
            front_redirect_target_pc_r      <= resolve_real_target;
            front_redirect_fallthrough_pc_r <= resolve_pc + 32'd4;
        end
    end
`ifndef SYNTHESIS
    // Cycle-for-cycle equivalence check for the split redirect-event boundary.
    // At this sampling edge the front event contains the previous cycle's two
    // local mispredict events, exactly as the former single register did.
    reg expected_front_redirect_valid_r;
    always @(posedge cpu_clk) begin
        if (!cpu_rstn)
            expected_front_redirect_valid_r <= 1'b0;
        else begin
            if (front_redirect_valid !== expected_front_redirect_valid_r)
                $fatal(1, "split redirect register changed event timing");
            expected_front_redirect_valid_r <= id2_mispredict;
        end
