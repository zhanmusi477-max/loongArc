    // boundary.  Selecting its low/high byte with offset[0] is exactly the
    // former four-way word-byte mux, but keeps unrelated word bits out of the
    // OF branch-compare and redirect cone.
    assign load_result_byte_of_r = load_result_offset_of_r[0]
                                 ? load_result_half_of_r[15:8]
