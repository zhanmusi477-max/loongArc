    // aligned Load, the pre-aligned byte candidate is the architectural low
    // byte.  Likewise, a non-byte result's bits [15:8] already equal the upper
    // byte of the pre-aligned half candidate.  This keeps is_half out of bits
    // [15:0], so a dependent ADD does not carry that late type select through
    // all eight CARRY4 stages.  The DCache-to-result register boundary and the
    // externally visible Load valid cycle remain unchanged.
