    // Parallel commit sideband.  It advances on exactly the same enables as
    // EX/M1/M2 and reaches slot 2 on the edge that the instruction enters WB.
    // CSR serializes younger issue until this point so a following address
    // translation cannot observe stale CRMD/DMW state.
    integer sys_i;
    always @(posedge cpu_clk) begin
        if (!cpu_rstn) begin
            sys_valid_pipe   <= 3'b0;
            csr_we_pipe      <= 3'b0;
            cacop_valid_pipe <= 3'b0;
            for (sys_i = 0; sys_i < 3; sys_i = sys_i + 1) begin
                csr_num_pipe[sys_i]   <= 14'b0;
                csr_wmask_pipe[sys_i] <= 32'b0;
                csr_wdata_pipe[sys_i] <= 32'b0;
                cacop_code_pipe[sys_i] <= 5'b0;
                cacop_addr_pipe[sys_i] <= 32'b0;
            end
        end else if (!pl_suspend) begin
            sys_valid_pipe   <= {sys_valid_pipe[1:0],
                                 (of_csr_we | of_cacop_valid)};
            csr_we_pipe      <= {csr_we_pipe[1:0], of_csr_we};
            cacop_valid_pipe <= {cacop_valid_pipe[1:0],
                                 of_cacop_valid};
            csr_num_pipe[0] <= of_csr_num;
            csr_wmask_pipe[0] <= of_csr_wmask;
            csr_wdata_pipe[0] <= of_csr_wdata;
            cacop_code_pipe[0] <= of_cacop_code;
            cacop_addr_pipe[0] <= of_cacop_addr;
            for (sys_i = 1; sys_i < 3; sys_i = sys_i + 1) begin
                csr_num_pipe[sys_i] <= csr_num_pipe[sys_i-1];
                csr_wmask_pipe[sys_i] <= csr_wmask_pipe[sys_i-1];
                csr_wdata_pipe[sys_i] <= csr_wdata_pipe[sys_i-1];
                cacop_code_pipe[sys_i] <= cacop_code_pipe[sys_i-1];
                cacop_addr_pipe[sys_i] <= cacop_addr_pipe[sys_i-1];
            end
        end
    end

    assign icache_inv  = cacop_valid_pipe[2] && !pl_suspend &&
                         (cacop_code_pipe[2] == 5'h00);
    assign dcache_inv  = cacop_valid_pipe[2] && !pl_suspend &&
                         ((cacop_code_pipe[2] == 5'h01) ||
                          (cacop_code_pipe[2] == 5'h09));
    assign cacheop_addr = cacop_addr_pipe[2];

